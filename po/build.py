#!/usr/bin/env python3
"""Build the Nothing KDE translation catalogs from gettext sources.

po/panel/nothing-panel.pot  island and dock strings; msgctxt is the key the QML
                            passes to Cfg.t(), msgid the English text
po/panel/<lang>.po          translations of that template
po/widgets/<lang>.po        desktop widget strings (English msgid, i18n())

The panel catalog becomes contents/island/ui/Translations.js, so the island
keeps its own language choice; the widgets get KDE .mo catalogs. A new
language is a new <lang>.po. --check verifies without writing.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PANEL = ROOT / 'po/panel'
TEMPLATE = PANEL / 'nothing-panel.pot'
CATALOG = ROOT / 'plasmoids/com.nothingplasma.panel/contents/island/ui/Translations.js'
WIDGETS = ROOT / 'widgets/packages'


def parse(path):
    """{(msgctxt, msgid): msgstr} for a .po/.pot file, header excluded."""
    entries, current, field = {}, {}, None

    def flush():
        if current.get('msgid'):
            entries[(current.get('msgctxt'), current['msgid'])] = current.get('msgstr', '')
        current.clear()

    for number, line in enumerate(path.read_text().splitlines(), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            if not line: flush()
            continue
        keyword, _, rest = line.partition(' ')
        if keyword in ('msgctxt', 'msgid', 'msgstr'):
            if keyword in current or (keyword == 'msgctxt' and 'msgid' in current): flush()
            field, line = keyword, rest
        elif not line.startswith('"') or field is None:
            raise SystemExit(f'{path}:{number}: unsupported line')
        current[field] = current.get(field, '') + json.loads(line)
    flush()
    return entries


def msgfmt_check(path):
    subprocess.run(['msgfmt', '--check', '-o', '/dev/null', str(path)], check=True)


def panel_catalogs():
    template = parse(TEMPLATE)
    english = {context: msgid for (context, msgid) in template}
    catalogs = {'en': english}
    problems = []
    for po in sorted(PANEL.glob('*.po')):
        msgfmt_check(po)
        language, entries = po.stem, parse(po)
        stale = [context for (context, msgid) in entries if english.get(context) != msgid]
        missing = [context for context in english if (context, english[context]) not in entries]
        problems += [f'{po.name}: stale entry {key!r}' for key in stale]
        problems += [f'{po.name}: missing {key!r}' for key in missing]
        catalogs[language] = {context: text for (context, msgid), text in entries.items() if text}
    return catalogs, problems


def panel_source(catalogs):
    languages = sorted(catalogs, key=lambda code: (code != 'en', code))
    body = json.dumps({code: dict(sorted(catalogs[code].items())) for code in languages},
                      ensure_ascii=False, indent=1, sort_keys=False)
    return ('// Generated by po/build.py from po/panel; edit the .po files instead.\n.pragma library\n\n'
            'var languages = ' + json.dumps(languages) + ';\nvar catalogs = ' + body + ';\n')


def widget_catalogs(check):
    import re
    problems = []
    for po in sorted((ROOT / 'po/widgets').glob('*.po')):
        msgfmt_check(po)
        language, entries = po.stem, {msgid: text for (_, msgid), text in parse(po).items()}
        # widgets/shared is copied into every package when it is staged.
        shared = list((ROOT / 'widgets/shared').rglob('*.qml'))
        for package in sorted(WIDGETS.iterdir()):
            strings = {json.loads(match) for qml in list(package.rglob('*.qml')) + shared for match in
                       re.findall(r'\bi18n\(\s*("(?:\\.|[^"\\])*")', qml.read_text())}
            problems += [f'{po.name}: missing {s!r} ({package.name})' for s in sorted(strings - entries.keys())]
            if check: continue
            domain = 'plasma_applet_org.nothingkde.widget.' + package.name
            target = package / 'contents/locale' / language / 'LC_MESSAGES' / (domain + '.mo')
            target.parent.mkdir(parents=True, exist_ok=True)
            # Only this package's strings go into its catalog.
            with tempfile.TemporaryDirectory(prefix='nothing-kde-i18n-') as temp:
                part = Path(temp) / (package.name + '.po')
                part.write_text(po.read_text().split('\n\n', 1)[0] + '\n\n' + ''.join(
                    'msgid ' + json.dumps(s, ensure_ascii=False) + '\nmsgstr ' + json.dumps(entries[s], ensure_ascii=False) + '\n\n'
                    for s in sorted(strings) if s in entries))
                subprocess.run(['msgfmt', '--check-format', '-o', str(target), str(part)], check=True)
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='verify sources and the generated catalog')
    args = parser.parse_args()
    catalogs, problems = panel_catalogs()
    problems += widget_catalogs(args.check)
    source = panel_source(catalogs)
    if args.check:
        if not CATALOG.is_file() or CATALOG.read_text() != source:
            problems.append(f'{CATALOG.relative_to(ROOT)} is out of date; run po/build.py')
    else:
        CATALOG.write_text(source)
    if problems:
        sys.exit('\n'.join(problems))
    print('Translations ' + ('verified' if args.check else 'built') + ': panel ' + ', '.join(sorted(catalogs)))


if __name__ == '__main__':
    main()
